"""Write the round-2 data configs from round 1's arm E (configs/train-data-h.yaml, configs/train-data-i.yaml).

Both keep E's sources, versions, exclusions, batching and replay, read the catalog copied to shared/catalog, and make
the configured augmentation actually reach the data (code patch PR #99 in shared/code):
- speed perturbation: every sample one of 0.95 / 1.0 / 1.05, timestamped SOT included (targets retimed);
- SpecAugment on half the samples, one time mask per 20 s (<= 0.5 s each) and two frequency masks (<= 16 of 128 bins).
Noise stays as in E (MUSAN, real recordings excluded): unchanged here so that H differs from E in speed and masking only.

I additionally scales the AliMeeting / AISHELL-4 real-meeting sources (both views) to a third of their weight; every
other source keeps its relative weight and the total is renormalized, so those meetings are heard ~5 instead of
~11-13 times per round (tasks/05-train-fit of round 1).
"""
from pathlib import Path

import yaml

RUN = Path(__file__).resolve().parents[1]
ROUND1 = RUN.parent / "zh-diar-ts-aux-acp-20261028"
REAL_MEETINGS = {"aishell4_meeting_sot", "alimeeting_sdm_meeting_sot"}
REAL_MEETING_SCALE = 1 / 3

AUGMENTATION = {
    "speed_prob": 1.0,
    # 0.95 keeps the longest 600 s window (631.6 s) under the 650 s batch budget.
    "speed_factors": [0.95, 1.0, 1.05],
    "spec_aug_prob": 0.5,
    "time_masks_per_second": 0.05,
    "time_mask_width": 50,
    "frequency_masks": 2,
    "frequency_mask_width": 16,
}


def main():
    base = yaml.safe_load((ROUND1 / "configs/train-data-e.yaml").read_text())
    base["catalog"] = str(RUN / "shared/catalog")
    base["roots"] = str(RUN / "shared/roots.json")
    base["augmentation"] = {**base["augmentation"], **AUGMENTATION}
    header = "# Generated by scripts/make_recipes.py from round 1's configs/train-data-e.yaml; do not edit by hand.\n"
    (RUN / "configs/train-data-h.yaml").write_text(header + yaml.safe_dump(base, sort_keys=False, allow_unicode=True))
    total = sum(s["weight"] for s in base["train"])
    for source in base["train"]:
        if source["dataset_id"] in REAL_MEETINGS and source["version"] in {
                "real-meetings-v2-20261010", "meeting-channel-view-v2-20261010"}:
            source["weight"] *= REAL_MEETING_SCALE
    scale = total / sum(s["weight"] for s in base["train"])
    for source in base["train"]:
        source["weight"] *= scale
    (RUN / "configs/train-data-i.yaml").write_text(header + yaml.safe_dump(base, sort_keys=False, allow_unicode=True))


if __name__ == "__main__":
    main()
