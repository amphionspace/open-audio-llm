"""Write the control training's configs from round 2's arm I (方案第 3 步, ../zh-diar-sim-real-gap-20261031/README.md).

configs/train-data-control.yaml keeps arm I's sources, weights, augmentation, batching and validation, except:
- the online meetings take the weight of what they replace: arm I's multi-speaker read mixes (sot_multispeaker_zh_en, >= 2
  speakers), three quarters of the word-level many-speaker mixes, half of the Emilia2 dialogues (it teaches "dialogues
  without overlap": 1.2% overlap time). A quarter of the many-speaker mixes stays because 6-12 speakers are a retention gate
  and the online meetings hardly go above 5.
- the windows take AliMeeting real meetings' 30 / 120 / 300 s proportions (its 600 s windows have no template here).
- synthesized meetings are out of waveform noise, as every real recording of arm I's recipe is.
configs/train-control.yaml and select-control.yaml are arm I's with this run's paths, the code snapshot in shared/code and
the smoothed paired rule; shared/baseline-step0.json adds the start model's window-level errors, the mean of the three
default decodes of ../zh-diar-sim-real-gap-20261031/tasks/01-decode-noise, to arm I's baseline.
"""
import json
from collections import defaultdict
from pathlib import Path

import yaml

RUN = Path(__file__).resolve().parents[1]
ARM_I = RUN.parent / "zh-diar-aug-acp-20261030"
GAP = RUN.parent / "zh-diar-sim-real-gap-20261031"
EMILIA2_KEEP = 0.5
MANY_SPEAKER_KEEP = 0.25
LENGTHS = {"train_30s": 1.99, "train_120s": 0.681, "train_300s": 0.417}  # arm I's alimeeting_sdm lines, one view
# Snapshot of the branch after merging main again (2026-11-03: #109 keeps training audio within full scale, as PCM16
# input is), so the PR carries the code the run trains with; code-control is the pre-merge snapshot the first preflight
# passed on, code-control-v2 the one the GPU smoke (tasks/15-control-smoke) ran.
CODE = "code-control-v3"
# api.wandb.ai refuses ACP egress; the pod reaches the development machine, where a forwarder on this port relays only
# the pod's IP to the local overseas proxy (arm I's tracking ended "远端结束状态未核实" without it).
WANDB_FORWARD = "http://10.119.16.21:17922"


def data_config():
    data = yaml.safe_load((ARM_I / "configs/train-data-i.yaml").read_text())
    synth = yaml.safe_load((RUN / "configs/synth-v1.yaml").read_text())
    online = synth["online_meeting"]
    data["catalog"], data["roots"] = synth["catalog"], synth["roots"]
    moved, train = 0.0, []
    for source in data["train"]:
        if source["dataset_id"] == "sot_multispeaker_zh_en" and "1spk" not in source["split"]:
            moved += source["weight"]
            continue
        keep = {"sot_many_speaker_word_zh_en": MANY_SPEAKER_KEEP, "emilia2_zh_dialogue_diarize": EMILIA2_KEEP}.get(source["dataset_id"])
        if keep is not None:
            moved += source["weight"] * (1 - keep)
            source["weight"] *= keep
        train.append(source)
    total = sum(LENGTHS.values())
    for split, share in LENGTHS.items():
        train.append({"dataset_id": online["material"]["dataset_id"], "version": online["material"]["version"], "split": split,
                      "max_duration": 650, "weight": moved * share / total, "online_meeting": online})
    data["train"] = train
    data["augmentation"]["noise_exclude_datasets"] = sorted({*data["augmentation"]["noise_exclude_datasets"], online["material"]["dataset_id"]})
    header = "# Generated by scripts/make_control_configs.py from arm I's configs/train-data-i.yaml; do not edit by hand.\n"
    (RUN / "configs/train-data-control.yaml").write_text(header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True))
    return moved


def replace_paths(text):
    return text.replace(str(ARM_I), str(RUN)).replace("zh-diar-aug-acp-20261030", RUN.name).replace("shared/code/", f"shared/{CODE}/")


def train_config():
    text = (ARM_I / "configs/train-i.yaml").read_text()
    text = text.split("\n", 1)[1]
    text = replace_paths(text).replace("configs/train-data-i.yaml", "configs/train-data-control.yaml")
    text = text.replace("../tasks/02-train-i/attempts", "../tasks/10-train-control/attempts")
    text = text.replace("AmphionASR-zh-diar-r2-i-speed-specaug-real-meetings-third", "AmphionASR-zh-diar-synth-control-online-meetings-from-emilia2")
    text = text.replace("tasks/03-select-i/control", "tasks/11-select-control/control")
    text = text.replace("priority: HIGHEST", "priority: NORMAL")
    steps = "  stage_max_steps: 12000\n"
    assert text.count(steps) == 1
    text = text.replace(steps, steps + "  expected_world_size: 8\n")
    # NumPy's hugepage advice makes page faults compact memory where THP defrag is "madvise": 64 MB took 50-70 s on the
    # local host (tasks/09-material-audit/README.md). The synthesizer allocates long arrays for every window.
    alloc = "    PYTORCH_ALLOC_CONF: expandable_segments:True\n"
    assert text.count(alloc) == 1
    text = text.replace(alloc, alloc + "    NUMPY_MADVISE_HUGEPAGE: '0'\n"
                        f"    WANDB_HTTP_PROXY: {WANDB_FORWARD}\n    WANDB_HTTPS_PROXY: {WANDB_FORWARD}\n")
    head = "# 对照训练（方案第 3 步）：I 组配方 + 在线重配音会议，见 scripts/make_control_configs.py。用户 2026-11-01：优先级调低，等已有任务跑完。\n"
    (RUN / "configs/train-control.yaml").write_text(head + text)


def smoke_config():
    """tasks/15-control-smoke: the control training on one local GPU for a few steps (user 2026-11-02: GPU 0), to check the merged code
    trains end to end on online meetings: model load, loss, data-loader waits, W&B. Not a result run, nothing is saved."""
    config = yaml.safe_load((RUN / "configs/train-control.yaml").read_text())
    del config["cluster"], config["storage"]
    runtime = config["runtime"]
    # Attempt 002 ran out of memory on GPU 0 at the first optimizer step: a 062 evaluation server and other users took 52 GB
    # there meanwhile. GPU 5 had 45 GB free at 21:05.
    runtime["gpus"], runtime["distributed"] = [5], {"processes": 1, "port": 29788}
    runtime["environment"].update(WANDB_HTTP_PROXY="http://127.0.0.1:17910", WANDB_HTTPS_PROXY="http://127.0.0.1:17910")
    arguments = config["task"]["arguments"]
    # Samples per step come from the data config's batching (max_samples 2), so the batch-size argument does not change them;
    # no accumulation keeps 40 steps short.
    arguments.update({"--per_device_train_batch_size": 1, "--gradient_accumulation_steps": 1, "--max_steps": 40,
                      "--warmup_steps": 5, "--save_strategy": "no", "--logging_steps": 1})
    del arguments["--save_steps"]
    preflight = config["preflight"][0]["arguments"]
    preflight["--batch-size"], preflight["--world-size"] = 1, 1
    config["recording"]["attempts_dir"]["path"] = "../tasks/15-control-smoke/attempts"
    config["tracking"]["name"] = "AmphionASR-zh-diar-synth-control-smoke-gpu0"
    config["parameters"]["stage_max_steps"] = 40
    config["parameters"]["expected_world_size"] = 1
    head = "# Generated by scripts/make_control_configs.py from configs/train-control.yaml (smoke_config); do not edit by hand.\n"
    (RUN / "configs/train-control-smoke.yaml").write_text(head + yaml.safe_dump(config, sort_keys=False, allow_unicode=True))


def select_config():
    data = (ARM_I / "configs/select-i.yaml").read_text()
    data = data.replace("AmphionASR-zh-diar-r2-i-select", "AmphionASR-zh-diar-synth-control-select")
    data = data.replace("../tasks/03-select-i", "../tasks/11-select-control").replace("../tasks/02-train-i", "../tasks/10-train-control")
    lines, skip = [], False
    for line in data.splitlines():
        if line.startswith("  previous_state:") or line.startswith("  # 10-30 21:37") or line.startswith("  # 已评的保存点"):
            continue
        lines.append(line)
    data = "\n".join(lines) + "\n"
    for name in ("eval-step8000-panel", "eval-step8000-many70", "eval-asr-dev", "eval-train-fit", "eval-step8000-meeting180", "eval-step8000-chime6",
                 "eval-step8000-fixed", "eval-final-aishell5-dev", "eval-final-cs-dialogue-test", "serve-step8000"):
        data = data.replace(f"{{path: {name}.yaml}}", f"{{path: ../../zh-diar-aug-acp-20261030/configs/{name}.yaml}}")
    data = data.replace("  patience: 3\n", "  patience: 3\n  # 平滑配对规则（../zh-diar-sim-real-gap-20261031）：连续 3 个合格保存点逐窗口平均，与起点配对 bootstrap，95% 区间整体 < 0 才算提升。\n  smoothing: 3\n")
    data = data.replace("../shared/code/src", f"../shared/{CODE}/src")
    data = data.replace("{path: ../shared/alimeeting-dev-voice-similarity.json}", "{path: ../../zh-diar-aug-acp-20261030/shared/alimeeting-dev-voice-similarity.json}")
    (RUN / "configs/select-control.yaml").write_text(data)


def baseline():
    base = json.loads((ARM_I / "shared/baseline-step0.json").read_text())
    pooled = defaultdict(list)
    for repeat in (1, 2, 3):
        path = GAP / f"tasks/01-decode-noise/attempts/001/artifacts/checkpoints/step-start-default/selection-r{repeat}/attempts/001/artifacts/evaluation/meeting-scores.jsonl"
        for line in path.read_text().splitlines():
            row = json.loads(line)
            if row.get("label") == "alimeeting_dev":
                pooled[row["id"]].append(row)
    base["target_windows"] = {k: [sum(r["cp_errors"] for r in rows) / len(rows), rows[0]["units"], any(r.get("repetition_loop") for r in rows)]
                              for k, rows in pooled.items()}
    errors = sum(v[0] for v in base["target_windows"].values() if not v[2])
    units = sum(v[1] for v in base["target_windows"].values() if not v[2])
    base["target"] = errors / units
    (RUN / "shared/baseline-step0.json").write_text(json.dumps(base, indent=2) + "\n")
    return len(pooled), base["target"]


if __name__ == "__main__":
    print("moved weight", round(data_config(), 3))
    train_config()
    smoke_config()
    select_config()
    print("baseline windows, target", baseline())
